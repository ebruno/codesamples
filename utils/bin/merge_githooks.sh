#!/usr/bin/env bash
# Merge sub-project githooks into .githooks/hooks/
#
# Scans all immediate subdirectories for githooks/ or .githooks/ directories
# and merges their hooks into the top-level .githooks/hooks/ with subdir-name
# prefixes. Regenerates root dispatcher hooks (pre-commit, post-commit) that
# delegate to sub-project hooks when their files are staged/committed.
#
# Idempotent — safe to run multiple times.
# Usage: ./merge_githooks.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
HOOKS_DIR="$PROJECT_ROOT/.githooks/hooks"

mkdir -p "$HOOKS_DIR"

# ── Scan for sub-project githooks ──────────────────────────────────────
echo "Scanning for sub-project githooks directories..."
FOUND_SUBDIRS=()

while IFS= read -r -d '' dir; do
    dir_name="$(basename "$(dirname "$dir")")"
    # Skip root .githooks (the target itself)
    if [ "$dir" = "$PROJECT_ROOT/.githooks" ]; then
        continue
    fi
    echo "  Found: ${dir_name}/githooks"
    FOUND_SUBDIRS+=("$dir_name")

    # Copy hook files with <subdir>- prefix
    for hook_file in "$dir"/*; do
        if [ ! -f "$hook_file" ]; then
            continue
        fi
        hook_name="$(basename "$hook_file")"
        # Skip non-hook files
        case "$hook_name" in
            INSTALL.md|README.md|.required_directory|*.sample|*.md|*.txt)
                continue
                ;;
        esac
        target="$HOOKS_DIR/${dir_name}-${hook_name}"
        cp "$hook_file" "$target"
        chmod +x "$target"
        echo "    Copied: ${hook_name} -> ${dir_name}-${hook_name}"
    done
done < <(find "$PROJECT_ROOT" -maxdepth 3 -type d \( -name "githooks" -o -name ".githooks" \) -print0 2>/dev/null | sort -z)

echo ""
echo "Found $(printf '%s' "${#FOUND_SUBDIRS[@]}") sub-project(s): ${FOUND_SUBDIRS[*]:-none}"

# ── Generate root pre-commit dispatcher ─────────────────────────────────

cat > "$HOOKS_DIR/pre-commit" << 'PRECOMMIT_EOF'
#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────
#  AUTO-GENERATED by merge_githooks — do not edit directly.
#  Run merge_githooks.sh to regenerate after adding/removing sub-project hooks.
# ─────────────────────────────────────────────────────────────────────
declare -i exit_status=0

HOOK_DIR="$(cd "$(dirname "$0")" && pwd)"

# ── 1. YAML tab check (original root-level behavior) ────────────────

if [ -z "${GIT_HOOK_PRECOMMIT_TEST_MODE:-}" ]; then
    GIT_HOOK_PRECOMMIT_TEST_MODE=1
fi

if [ -f /etc/os-release ]; then
    . /etc/os-release
else
    os_name="$(uname -s)"
    if [ "${os_name}" = "Darwin" ] && [ -e "/usr/bin/sw_vers" ]; then
        ID="$(sw_vers -productName)"
        MACOS_VERSION_FULL="$(sw_vers -productVersion)"
        VERSION_ID="${MACOS_VERSION_FULL%.*}"
    else
        echo "[ERROR] Unable to determine OS version for ${os_name}"
        exit_status=1
    fi
fi

if [ ${exit_status} -eq 0 ]; then
    tmpfile="$(mktemp)"
    git diff --cached --name-only > "${tmpfile}"
    while IFS= read -r line; do
        if [[ "${line}" =~ \.yml$ ]] || [[ "${line}" =~ \.yaml$ ]]; then
            case ${ID} in
                macOS|MacOS|freebsd)
                    sed -i ".bak" -e 's/\t/    /g' "${line}"
                    ;;
                debian|rhel|fedora|ubuntu|arch)
                    sed -i.bak -e 's/\t/    /g' "${line}"
                    ;;
                *)
                    echo "[WARNING] Unsupported ID=${ID}, skipping tab removal."
                    exit_status=1
                    break
                    ;;
            esac
            if [ -f "${line}.bak" ]; then
                rm -f "${line}.bak"
            fi
        fi
    done < "${tmpfile}"
    rm -f "${tmpfile}"
fi

if [ ${GIT_HOOK_PRECOMMIT_TEST_MODE} -eq 0 ]; then
    exit_status=1
fi

# ── 2. Sub-project pre-commit dispatch ──────────────────────────────
# Each sub-project hook runs only when its directory has staged changes.
PRECOMMIT_EOF

# Append dispatch loop
if [ ${#FOUND_SUBDIRS[@]} -gt 0 ]; then
    cat >> "$HOOKS_DIR/pre-commit" << 'DISPATCH_HEADER'

staged_files="$(git diff --cached --name-only)"
DISPATCH_HEADER

    for subdir in "${FOUND_SUBDIRS[@]}"; do
        hook_path="$HOOKS_DIR/${subdir}-pre-commit"
        if [ -x "$hook_path" ]; then
            cat >> "$HOOKS_DIR/pre-commit" << DISPATCH_BLOCK
if printf '%s' "\$staged_files" | grep -q "^${subdir}/"; then
    echo "[pre-commit] Running ${subdir} hooks..."
    "${hook_path}" || exit 1
fi
DISPATCH_BLOCK
        fi
    done
fi

cat >> "$HOOKS_DIR/pre-commit" << 'PRECOMMIT_FOOTER'

exit ${exit_status}
PRECOMMIT_FOOTER

chmod +x "$HOOKS_DIR/pre-commit"
echo "  Generated: pre-commit (dispatcher)"

# ── Generate root post-commit dispatcher ────────────────────────────────

cat > "$HOOKS_DIR/post-commit" << 'POSTCOMMIT_HEADER'
#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────
#  AUTO-GENERATED by merge_githooks — do not edit directly.
#  Run merge_githooks.sh to regenerate after adding/removing sub-project hooks.
# ─────────────────────────────────────────────────────────────────────

HOOK_DIR="$(cd "$(dirname "$0")" && pwd)"

# Sub-project post-commit dispatch.
# Each sub-project hook runs only when its directory was in the commit.
POSTCOMMIT_HEADER

if [ ${#FOUND_SUBDIRS[@]} -gt 0 ]; then
    for subdir in "${FOUND_SUBDIRS[@]}"; do
        hook_path="$HOOKS_DIR/${subdir}-post-commit"
        if [ -x "$hook_path" ]; then
            cat >> "$HOOKS_DIR/post-commit" << DISPATCH_BLOCK
if git diff --name-only HEAD~1 HEAD 2>/dev/null | grep -q "^${subdir}/"; then
    echo "[post-commit] Running ${subdir} hooks..."
    "${hook_path}" || true
fi
DISPATCH_BLOCK
        fi
    done
fi

cat >> "$HOOKS_DIR/post-commit" << 'POSTCOMMIT_FOOTER'

exit 0
POSTCOMMIT_FOOTER

chmod +x "$HOOKS_DIR/post-commit"
echo "  Generated: post-commit (dispatcher)"

# ── Summary ─────────────────────────────────────────────────────────────
echo ""
echo "Merge complete. To activate:"
echo "  git config core.hooksPath .githooks/hooks"
