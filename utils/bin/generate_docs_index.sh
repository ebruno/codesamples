#!/usr/bin/env bash
# Generate docs/index.html (GitHub) or pages/index.html (GitLab)
# Usage: generate_docs_index.sh <github|gitlab>

set -euo pipefail

MODE="${1:-}"
if [ "$MODE" != "github" ] && [ "$MODE" != "gitlab" ]; then
    echo "Usage: $0 <github|gitlab>" >&2
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
CODESAMPLES_DIR="$(cd "${SCRIPT_DIR}/.." && cd ".." && pwd)"

if [ "$MODE" = "github" ]; then
    MODE_DIR="docs"
    INDEX="${CODESAMPLES_DIR}/docs/index.html"
    TITLE="Codesamples GitHub Pages"
    COLOR="#0366d6"
else
    MODE_DIR="pages"
    INDEX="${CODESAMPLES_DIR}/pages/index.html"
    TITLE="Codesamples GitLab Pages"
    COLOR="#e24329"
fi

get_project_desc() {
    subdir="$1"
    readme="${CODESAMPLES_DIR}/${subdir}/README.md"
    
    if [ -f "$readme" ]; then
        desc=""
        while IFS= read -r line; do
            case "$line" in
                \#\ #*|\#\#*)
                    desc="${line##\#\# }"
                    desc="${desc#\# }"
                    break
                    ;;
            esac
        done < "$readme" || true
        
        if [ -n "$desc" ]; then
            echo "$desc"
            return
        fi
    fi
    
    echo "Documentation for ${subdir}"
}

is_skip_dir() {
    case "$1" in
        utils|docs|pages) return 0 ;;
        *) return 1 ;;
    esac
}

generate_index() {
    
    mkdir -p "$(dirname "${INDEX}")"
    
    cards=""
    found=0
    
    for subdir in ${CODESAMPLES_DIR}/*/; do
        dir_name=$(basename "$subdir")
        
        if is_skip_dir "$dir_name"; then
            continue
        fi
        
        project_index="${CODESAMPLES_DIR}/${MODE_DIR}/${dir_name}/index.html"
        if [ -f "$project_index" ]; then
            found=1
            desc=$(get_project_desc "$dir_name")
            
            cards="${cards}
    <div class=\"project-card\">
        <h2>${dir_name}</h2>
        <a href=\"${dir_name}/index.html\" style=\"color: ${COLOR};\">View Documentation →</a>
    </div>"
        fi
    done
    
    if [ $found -eq 0 ]; then
        cards="
    <div class=\"project-card\">
        <h2>No Documentation Available</h2>
        <p>Run <code>make publish-to-${MODE}</code> to generate documentation first.</p>
    </div>"
    fi
    
    cat > "${INDEX}" << EOF
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${TITLE}</title>
    <style>
        body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; max-width: 800px; margin: 40px auto; padding: 0 20px; color: #333; }
        h1 { border-bottom: 2px solid ${COLOR}; padding-bottom: 10px; }
        .project-card { border: 1px solid #e1e4e8; border-radius: 6px; padding: 20px; margin: 16px 0; }
        .project-card h2 { margin-top: 0; color: #333; }
        .project-card a { display: inline-block; background-color: #0366d6; color: #ffffff !important; padding: 8px 16px; border-radius: 4px; text-decoration: none; font-weight: bold; }
        .project-card a:hover { background-color: #0256b9; }
    </style>
</head>
<body>
    <h1>${TITLE}</h1>

${cards}

    <hr>
    <p><small>Auto-generated by generate_docs_index.sh</small></p>
</body>
</html>
EOF
    
    echo "Generated: ${INDEX}"
}

generate_index
